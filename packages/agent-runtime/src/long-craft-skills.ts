function normalizeSkillQuery(value: string): string {
  return value.trim().toLowerCase().replace(/\s+/g, " ");
}

export function resolveBuiltinLongCraftSkill(
  query: string
): BuiltinLongCraftSkill | undefined {
  const normalized = normalizeSkillQuery(query);
  if (!normalized) return undefined;
  return BUILTIN_LONG_CRAFT_SKILLS.find((skill) => {
    if (normalizeSkillQuery(skill.id) === normalized) return true;
    if (normalizeSkillQuery(skill.name) === normalized) return true;
    return skill.aliases.some(
      (alias) => normalizeSkillQuery(alias) === normalized
    );
  });
}

export function formatBuiltinLongCraftSkillResult(
  skill: BuiltinLongCraftSkill
): string {
  return [
    `已加载内置长篇网文技法技能：${skill.name}（${skill.id}）`,
    `适用场景：${skill.summary}`,
    "",
    skill.content
  ].join("\n");
}
